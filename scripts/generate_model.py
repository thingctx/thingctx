"""Generate the record classes and vocabulary tables from a model's records.yaml.

Writes three files into the model's ``_generated`` directory:

    records.py           the pydantic classes. Exactly what this command writes:
                         gen-pydantic --meta None --emptylist-for-multivalued-slots
                             --template-dir scripts/model_templates records.yaml
    records.schema.json  exactly what ``gen-json-schema records.yaml`` writes
    terms.py             the vocabulary tables, written by this script

LinkML writes the first two unchanged, so anyone running those commands by hand gets
the same bytes. linkml is pinned to one version for that reason.

This script writes terms.py itself because LinkML's RDF generators (gen-owl,
gen-jsonld-context) invent a new term for every class and field. thingctx publishes
only terms from SOSA, PROV-O, schema.org, DCAT and Dublin Core, and a field with no
published term is simply left out of the JSON-LD.

Usage:
  generate_model.py [MODEL ...]           rewrite; default is every model found
  generate_model.py --check               exit 1 if any output is stale

Needs the ``models`` extra, in its own environment.
"""

from __future__ import annotations

import argparse
import difflib
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

MODELS = Path(__file__).resolve().parent.parent / "src" / "thingctx" / "models"
TEMPLATES = Path(__file__).resolve().parent / "model_templates"

# Every generated class inherits Record from models/_base.py. The jinja templates
# add that base and bind the model's tables to it.
BASE = "Record"
BASE_MODULE = "thingctx.models._base"
BOUND = "VocabularyRecord"

_BOUND_CLASS = f"""class {BOUND}({BASE}):
    \"\"\"{BASE} bound to this model's vocabulary.\"\"\"

    _CONTEXT = CONTEXT
    _TERMS = TERMS
    _TYPES = TYPES
    _IDENTITY = IDENTITY
    _ID_NAMESPACE = ID_NAMESPACE
    _NESTED = NESTED
    _STATUS_IRI = STATUS_IRI
"""


def _out(model: Path) -> Path:
    """The directory this script writes into. One directory, so the tree shows what
    is generated."""
    return model / "_generated"


def discover() -> list[Path]:
    """Every model directory under src/thingctx/models that has a records.yaml."""
    return sorted(path.parent for path in MODELS.glob("*/records.yaml"))


# Fields that do not become a direct JSON-LD predicate. The schema marks them with
# ``annotations: projection: <value>``.
_NOT_A_PREDICATE = frozenset({"identifier", "row_only", "instrument"})

_PACKAGE = """# Copyright 2026 The thingctx Authors
# SPDX-License-Identifier: Apache-2.0
\"\"\"Generated by scripts/generate_model.py from records.yaml. Do not edit.\"\"\"
"""

_TABLES = ("CONTEXT", "TERMS", "TYPES", "IDENTITY", "ID_NAMESPACE", "NESTED", "STATUS_IRI")

_HEADER_FOR_RECORDS = """# Copyright 2026 The thingctx Authors
# SPDX-License-Identifier: Apache-2.0
# Generated from records.yaml by scripts/generate_model.py. Do not edit.
"""

_HEADER = '''# Copyright 2026 The thingctx Authors
# SPDX-License-Identifier: Apache-2.0
"""Generated from records.yaml by scripts/generate_model.py. Do not edit.

Run ``scripts/generate_model.py`` after changing the schema. CI fails if this
file and the schema disagree.
"""

from __future__ import annotations

__all__ = [
    "CONTEXT",
    "IDENTITY",
    "ID_NAMESPACE",
    "NESTED",
    "OUTCOMES",
    "STATUS_IRI",
    "TERMS",
    "TYPES",
]

'''


def _annotation(element: Any, name: str, default: str | None = None) -> str | None:
    """Read one schema annotation. LinkML hands back a dict for a class and a JsonObj
    for a slot, so both are handled."""
    holder = element.annotations
    if not holder:
        return default
    found = holder.get(name) if isinstance(holder, dict) else holder._get(name)
    return default if found is None else str(found.value)


def _render(name: str, value: object, comment: str) -> str:
    body = json.dumps(value, indent=4, sort_keys=False)
    body = body.replace("[", "(").replace("]", ")") if isinstance(value, tuple) else body
    return f"# {comment}\n{name} = {body}\n\n"


def build(model: Path) -> str:
    from linkml_runtime import SchemaView  # noqa: PLC0415

    view = SchemaView(str(model / "records.yaml"))
    classes = [name for name, c in view.all_classes().items() if c.class_uri != "linkml:Any"]

    terms: dict[str, dict[str, str]] = {}
    types: dict[str, list[str]] = {}
    nested: dict[str, dict[str, Any]] = {}
    used: set[str] = set()

    for class_name in classes:
        definition = view.get_class(class_name)
        mapping: dict[str, str] = {}
        for slot_name in view.class_slots(class_name):
            slot = view.induced_slot(slot_name, class_name)
            if _annotation(slot, "projection") in _NOT_A_PREDICATE or slot.identifier:
                continue
            mapping[slot_name] = slot.slot_uri
            used.add(slot.slot_uri.split(":", 1)[0])
        terms[class_name] = mapping

        # Fields the schema groups into one nested JSON-LD node.
        node: dict[str, Any] = {"terms": {}}
        for slot_name in view.class_slots(class_name):
            slot = view.induced_slot(slot_name, class_name)
            if _annotation(slot, "projection") != "instrument":
                continue
            under = _annotation(slot, "nested_under")
            if under is not None:
                node["predicate"] = under
                node["type"] = _annotation(slot, "nested_type")
                node["id_from"] = slot_name
                used.update(iri.split(":", 1)[0] for iri in (under, node["type"]))
            else:
                node["terms"][slot_name] = slot.slot_uri
                used.add(slot.slot_uri.split(":", 1)[0])
        if "predicate" in node:
            nested[class_name] = node

        # A record can carry two @type values, for example sosa:Actuation and
        # schema:Action.
        iris = [definition.class_uri]
        extra = _annotation(definition, "also_typed_as")
        if extra is not None:
            iris.append(extra)
        types[class_name] = iris
        used.update(iri.split(":", 1)[0] for iri in iris)

    identity = {
        name: _annotation(view.get_class(name), "identity", "").split(",") for name in classes
    }
    namespaces = {
        name: found
        for name in classes
        if (found := _annotation(view.get_class(name), "id_namespace")) is not None
    }

    status: dict[str, str] = {}
    outcomes: dict[str, tuple[str, ...]] = {}
    for enum_name, enum in view.all_enums().items():
        values = tuple(enum.permissible_values)
        outcomes[enum_name] = values
        for value_name, value in enum.permissible_values.items():
            if value.meaning:
                status[value_name] = value.meaning
                used.add(value.meaning.split(":", 1)[0])

    # Only the namespaces a published term actually uses. The schema's own prefix is
    # never used, so it never appears.
    context = {p: str(view.namespaces()[p]) for p in sorted(used)}

    out = _HEADER
    out += _render("CONTEXT", context, "Prefix to namespace, for every term the records publish.")
    out += _render("TERMS", terms, "Record type, then field to the term it publishes as.")
    out += _render("TYPES", types, "The @type IRIs each record carries.")
    out += _render("NESTED", nested, "A pair that publishes as a node, not as two predicates.")
    out += _render("IDENTITY", identity, "The fields that make two records the same record.")
    out += _render(
        "ID_NAMESPACE", namespaces, "Record type to its own id namespace, where it has one."
    )
    out += _render("OUTCOMES", {k: list(v) for k, v in outcomes.items()}, "Enum to its values.")
    out += _render("STATUS_IRI", status, "Enum value to the IRI it means.")
    return _formatted(out, _out(model) / "terms.py")


def _formatted(source: str, like: Path) -> str:
    """Run ruff format over the text, so the committed file passes ruff format."""
    return subprocess.run(  # noqa: S603  # this interpreter, a fixed module
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(like)],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def build_records(model: Path) -> str:
    """The record classes, as gen-pydantic writes them. Nothing is changed afterwards."""
    from linkml.generators.pydanticgen import PydanticGenerator  # noqa: PLC0415

    return PydanticGenerator(
        str(model / "records.yaml"),
        metadata_mode=None,
        empty_list_for_multivalued_slots=True,
        template_dir=str(TEMPLATES),
    ).serialize()


def generate(model: Path) -> dict[Path, str]:
    """Every file to write for one model, keyed by path."""
    json_schema = subprocess.run(  # noqa: S603  # this interpreter, a fixed module
        [sys.executable, "-m", "linkml.generators.jsonschemagen", str(model / "records.yaml")],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    out = _out(model)
    return {
        out / "__init__.py": _PACKAGE,
        out / "terms.py": build(model),
        out / "records.py": build_records(model),
        out / "records.schema.json": json_schema,
    }


def _diff(current: str, fresh: str, path: Path) -> list[str]:
    """What the generator would change, so a failed check says why."""
    return list(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            fresh.splitlines(keepends=True),
            fromfile=f"committed {path.name}",
            tofile=f"generated {path.name}",
            n=1,
        )
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the output is stale")
    parser.add_argument("model", nargs="*", help="model name; default is every model found")
    args = parser.parse_args()

    wanted = [MODELS / name for name in args.model] if args.model else discover()
    if not wanted:
        print("no model found", file=sys.stderr)  # noqa: T201  # CLI output
        return 1

    stale: list[str] = []
    for model in wanted:
        for path, fresh in generate(model).items():
            if args.check:
                current = path.read_text() if path.exists() else ""
                if current != fresh:
                    stale.append(f"{model.name}/_generated/{path.name}")
                    sys.stdout.writelines(_diff(current, fresh, path))
                continue
            path.parent.mkdir(exist_ok=True)
            path.write_text(fresh)
            print(f"wrote {model.name}/_generated/{path.name}")  # noqa: T201  # CLI output

    if stale:
        print(  # noqa: T201  # CLI output
            f"stale, run scripts/generate_model.py: {', '.join(stale)}", file=sys.stderr
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
